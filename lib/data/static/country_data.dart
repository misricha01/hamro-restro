/// A country option for the Restaurant Details "Country" picker: display
/// name plus its ISO 3166-1 alpha-2 code, from which the flag emoji is
/// derived at runtime (regional-indicator symbols) instead of being hand
/// typed per entry, so it can never drift from [code].
class CountryOption {
  final String name;
  final String code;
  const CountryOption(this.name, this.code);

  String get flag {
    final cc = code.toUpperCase();
    const base = 0x1F1E6;
    return String.fromCharCode(base + cc.codeUnitAt(0) - 65) + String.fromCharCode(base + cc.codeUnitAt(1) - 65);
  }
}

